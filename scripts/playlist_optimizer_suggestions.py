#!/usr/bin/env python3
"""Read-only IPTV name/category normalization suggestions.

Produces proposals only. Never edits M3U playlists, never moves/deletes channels,
and never rewrites a protected category or user-approved title.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import pathlib
import re
import unicodedata
from datetime import datetime, timezone

ROOT = pathlib.Path(__file__).resolve().parents[1]
PLAYLISTS = ("CALISANLAR.m3u", "YENILER.m3u")
PROTECTED_MARKERS = ("FAVORİLER", "FAVORILER", "YEDEKLER", "HEPSİ", "HEPSI")
IMPORTANT = ("TRT 1", "DHA CANLI")
ATTR = re.compile(r'([\w-]+)="([^"]*)"')


def normalize_spaces(value: str) -> str:
    return " ".join(unicodedata.normalize("NFC", value).split())


def protected(group: str, title: str) -> bool:
    upper_group = group.upper()
    upper_title = title.upper()
    return any(marker in upper_group for marker in PROTECTED_MARKERS) or any(
        name in upper_title for name in IMPORTANT
    )


def propose(path: pathlib.Path) -> dict:
    raw = path.read_bytes()
    lines = raw.decode("utf-8-sig", errors="replace").splitlines()
    suggestions = []
    pending = None
    for line_no, line in enumerate(lines, 1):
        if line.lstrip().startswith("#EXTINF:"):
            attrs = dict(ATTR.findall(line))
            title = line.split(",", 1)[1] if "," in line else ""
            pending = (line_no, attrs, title)
            continue
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        if pending is None:
            continue
        meta_line, attrs, title = pending
        pending = None
        group = attrs.get("group-title", "")
        if protected(group, title):
            continue
        normalized_title = normalize_spaces(title)
        normalized_group = normalize_spaces(group)
        changes = {}
        if normalized_title and normalized_title != title:
            changes["channel_name"] = {"current": title, "suggested": normalized_title}
        if normalized_group and normalized_group != group:
            changes["category"] = {"current": group, "suggested": normalized_group}
        if not group:
            changes["category_review"] = "Missing group-title; manual categorization required."
        if not title.strip():
            changes["channel_name_review"] = "Empty channel title; manual naming required."
        if changes:
            suggestions.append({
                "extinf_line": meta_line,
                "url_line": line_no,
                "url_sha256": hashlib.sha256(line.strip().encode("utf-8")).hexdigest(),
                "changes": changes,
                "requires_manual_approval": True,
            })
    return {
        "file": path.name,
        "sha256": hashlib.sha256(raw).hexdigest(),
        "suggestion_count": len(suggestions),
        "suggestions": suggestions,
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--inventory", default="playlist_inventory.json",
                        help="Optional inventory JSON generated by playlist_inventory.py")
    parser.add_argument("--output", default="playlist_optimizer_suggestions.json")
    args = parser.parse_args()
    inventory_path = pathlib.Path(args.inventory)
    inventory = None
    if inventory_path.is_file():
        inventory = json.loads(inventory_path.read_text(encoding="utf-8"))
    inventory_sha = {}
    if isinstance(inventory, dict):
        inventory_sha = {
            row.get("file"): row.get("sha256")
            for row in inventory.get("playlists", [])
            if isinstance(row, dict)
        }
    reports = []
    for name in PLAYLISTS:
        path = ROOT / name
        if not path.is_file():
            reports.append({"file": name, "status": "missing", "suggestions": []})
            continue
        report = propose(path)
        expected = inventory_sha.get(name)
        report["inventory_sha256_matches"] = (
            expected == report["sha256"] if expected else None
        )
        reports.append(report)
    output = {
        "generated_utc": datetime.now(timezone.utc).isoformat(),
        "mode": "suggestions_only",
        "playlists_modified": False,
        "automatic_deletion": False,
        "automatic_movement": False,
        "inventory_file": str(inventory_path),
        "reports": reports,
    }
    dest = pathlib.Path(args.output)
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(json.dumps(output, ensure_ascii=False, indent=2) + "\n",
                    encoding="utf-8")
    for report in reports:
        print(f"{report['file']}: {report.get('suggestion_count', 0)} suggestions")
    print(f"Report: {dest}")


if __name__ == "__main__":
    main()
